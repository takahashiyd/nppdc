function C = paper_palette(name)
%PAPER_PALETTE  Named colours from a matplotlib-tab10-style palette.
%
%   C = paper_palette()         returns the 8x3 palette
%   c = paper_palette('blue')   returns 1x3 RGB
%
%   Names: blue, red, green, purple, orange, brown, pink, gray, black

    pal = struct( ...
        'blue',   [0.122 0.467 0.706], ...
        'red',    [0.839 0.153 0.157], ...
        'green',  [0.173 0.627 0.173], ...
        'purple', [0.580 0.404 0.741], ...
        'orange', [1.000 0.498 0.055], ...
        'brown',  [0.549 0.337 0.294], ...
        'pink',   [0.890 0.467 0.761], ...
        'gray',   [0.498 0.498 0.498], ...
        'black',  [0     0     0    ]);

    if nargin < 1 || isempty(name)
        C = [pal.blue; pal.red; pal.green; pal.purple; pal.orange; ...
             pal.brown; pal.pink; pal.gray];
    else
        C = pal.(lower(name));
    end
end
